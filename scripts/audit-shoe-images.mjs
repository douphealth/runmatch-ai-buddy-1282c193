#!/usr/bin/env node
/**
 * Audits public/images/shoes/*.jpg and writes src/lib/shoe-image-audit.ts.
 *
 * Problem this solves: the photo for a shoe is looked up by
 * `{brand}-{model}.jpg`, but the scrape that produced the files re-used one
 * photo for several different shoes (e.g. a Brooks Ghost 15 was saved as the
 * Saucony Ride 19, Hoka Cielo X1, Mizuno Wave Inspire 21 ...). Showing the wrong
 * shoe next to an affiliate button is a trust and conversion problem.
 *
 * Rule: if two or more files are byte-identical, at most ONE of them can be
 * right, and only a human can say which. So every member of a duplicate group
 * is treated as unverified (the UI shows the branded studio frame instead)
 * unless it is listed in VERIFIED_DUPLICATE_OWNERS below after someone has
 * looked at the picture and confirmed it shows that exact model. A file that is
 * identical to placeholder.jpg is always unverified.
 *
 * Usage:
 *   node scripts/audit-shoe-images.mjs          # rewrite src/lib/shoe-image-audit.ts
 *   node scripts/audit-shoe-images.mjs --check  # exit 1 if the generated file is stale
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = resolve(ROOT, 'public/images/shoes');
const OUT = resolve(ROOT, 'src/lib/shoe-image-audit.ts');

/**
 * Duplicate-group members whose photo has been checked by eye and does show
 * that exact model. Extend this list (and re-run) after verifying a photo.
 *   nike-pegasus-41          -> "Pegasus 41" (Air Zoom, ReactX) photo
 *   saucony-endorphin-pro-4  -> "ENDORPHIN PRO 4" printed on the shoe
 */
const VERIFIED_DUPLICATE_OWNERS = new Set(['nike-pegasus-41', 'saucony-endorphin-pro-4']);

const md5 = (file) => createHash('md5').update(readFileSync(file)).digest('hex');

const files = readdirSync(DIR).filter((f) => f.endsWith('.jpg'));
const byHash = new Map();
for (const f of files) {
  const h = md5(resolve(DIR, f));
  if (!byHash.has(h)) byHash.set(h, []);
  byHash.get(h).push(f.replace(/\.jpg$/, ''));
}

const placeholderHash = existsSync(resolve(DIR, 'placeholder.jpg')) ? md5(resolve(DIR, 'placeholder.jpg')) : null;

const unverified = new Set();
const groups = [];
for (const [hash, slugs] of byHash) {
  const isPlaceholder = placeholderHash && hash === placeholderHash;
  if (isPlaceholder) {
    for (const s of slugs) if (s !== 'placeholder') unverified.add(s);
    continue;
  }
  if (slugs.length > 1) {
    groups.push(slugs);
    for (const s of slugs) if (!VERIFIED_DUPLICATE_OWNERS.has(s)) unverified.add(s);
  }
}
unverified.delete('placeholder');

const sorted = [...unverified].sort();
const body = `/**
 * GENERATED by scripts/audit-shoe-images.mjs — do not edit by hand.
 * Re-run \`node scripts/audit-shoe-images.mjs\` after changing files in
 * public/images/shoes/.
 *
 * Image slugs (\`{brand}-{model}\`, see shoeImageSlug) whose photo is shared with
 * a different shoe (or is the generic placeholder) and therefore cannot be
 * trusted to show the right model. The UI renders the branded studio frame for
 * these instead of a wrong photo.
 */
export const UNVERIFIED_SHOE_IMAGE_SLUGS: ReadonlySet<string> = new Set([
${sorted.map((s) => `  '${s}',`).join('\n')}
]);
`;

if (process.argv.includes('--check')) {
  // Compare ignoring line endings: a Windows checkout (core.autocrlf) rewrites them.
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== body) {
    console.error('[audit-shoe-images] src/lib/shoe-image-audit.ts is out of date. Run: node scripts/audit-shoe-images.mjs');
    process.exit(1);
  }
  console.log(`[audit-shoe-images] up to date (${sorted.length} unverified of ${files.length - 1} photos)`);
} else {
  writeFileSync(OUT, body, 'utf8');
  console.log(`[audit-shoe-images] ${files.length - 1} photos, ${groups.length} duplicate groups, ${sorted.length} unverified -> src/lib/shoe-image-audit.ts`);
  for (const g of groups) console.log('  duplicate group:', g.join(', '));
}
