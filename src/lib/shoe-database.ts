const photoSlug = (s: Pick<Shoe, 'brand' | 'model'>) => `${s.brand}-${s.model}`.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/**
 * The one rule for being in the app: a shoe needs a SPECIFIC, verified Amazon listing (a /dp/ASIN link from
 * amazon-asin-cache.json, men's or unisex) AND the photo from that same listing (amazon-image-cache.json).
 * No guess, no search link, no maker-site stand-in, no placeholder picture. A shoe that fails this is not
 * recommended, listed, compared or given a page; it stays in the data file above and comes back by itself when
 * `node scripts/amazon-catalog.mjs resolve --write <id>` and `images --all` find a listing for it.
 */
export function isBuyable(shoe: Pick<Shoe, 'id' | 'brand' | 'model'>): boolean {
  const link = (asinCache as Record<string, { asin: string | null; title?: string }>)[shoe.id];
  if (!link?.asin || !/^[A-Z0-9]{10}$/.test(link.asin)) return false;
  const t = (link.title ?? '').toLowerCase();
  if (/\bwomen['’]?s?\b/.test(t) && !/\bmen['’]?s?\b/.test(t.replace(/women['’]?s?/g, ''))) return false; // women's-only version
  const photo = (imageCache as Record<string, { asin: string; url: string }>)[photoSlug(shoe)];
  return !!photo?.url && photo.asin === link.asin;
}

/** Everything in the data file, including shoes hidden because they cannot be bought on Amazon today. Tools only. */
export const allShoesIncludingHidden: Shoe[] = ALL_SHOES;

/** The shoes the app shows: only the ones that pass `isBuyable`. */
export const shoeDatabase: Shoe[] = ALL_SHOES.filter(isBuyable);

/**
 * Retired ids that still resolve (old links, saved matches, search results).
 * Key = retired id, value = the id that replaces it.
 */
export const SHOE_ID_ALIASES: Readonly<Record<string, string>> = {
  'nb-fresh-foam-1080-v14': 'nb-1080-v14',
};

/** Resolve a possibly-retired shoe id to its current id. */
export const resolveShoeId = (id: string): string => SHOE_ID_ALIASES[id] ?? id;

/**
 * Returns a direct Amazon product affiliate URL only when a verified ASIN exists.
 * Never falls back to Amazon search pages; callers should hide Amazon CTAs when null.
 */
export function getAmazonLink(asin: string | null | undefined, affiliateTag: string = 'papalex-20'): string | null {
  if (!asin || !/^[A-Z0-9]{10}$/.test(asin)) return null;
  return `https://www.amazon.com/dp/${asin}?tag=${affiliateTag}`;
}

/** Convenience helper that takes a Shoe directly. */
export function getShoeAmazonLink(shoe: Pick<Shoe, 'amazonASIN'>, affiliateTag: string = 'papalex-20'): string | null {
  return getAmazonLink(shoe.amazonASIN, affiliateTag);
}


export function getShoeQualityState(shoe: Shoe) {
  const isPlaceholderImage = !shoe.imageURL || shoe.imageURL.includes('placeholder');
  const hasSpecificReview = Boolean(shoe.reviewURL && !shoe.reviewURL.endsWith('/review/best-running-shoes/'));
  const hasVerifiedAffiliate = Boolean(shoe.amazonASIN && shoe.amazonASIN !== 'SEARCH');
  const dataQualityNotes = [
    isPlaceholderImage ? 'placeholder image' : '',
    !shoe.sourceURL ? 'missing authoritative source URL' : '',
    !hasSpecificReview ? 'generic or missing review URL' : '',
    !hasVerifiedAffiliate ? 'affiliate target needs verification' : '',
  ].filter(Boolean);
  const isRecommendationReady = shoe.isRecommendationReady ?? Boolean(shoe.brand && shoe.model && shoe.category && shoe.bestFor?.length && shoe.terrain?.length);
  const isAffiliateReady = shoe.isAffiliateReady ?? hasVerifiedAffiliate;
  const isIndexable = shoe.isIndexable ?? (isRecommendationReady && isAffiliateReady && !isPlaceholderImage && Boolean(shoe.sourceURL) && hasSpecificReview && dataQualityNotes.length === 0);
  return { isRecommendationReady, isAffiliateReady, isIndexable, dataQualityNotes };
}
